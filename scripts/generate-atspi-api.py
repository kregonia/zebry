#!/usr/bin/env python3
"""Regenerate the small Zig ABI module from installed AT-SPI2 headers.

Normal builds use the checked-in module and do not require Python or this step.
Only pointer types are made opaque; no GObject implementation layouts are used.
"""
import pathlib
import re
import shlex
import subprocess

root = pathlib.Path(__file__).resolve().parents[1]
flags = shlex.split(subprocess.check_output(
    ["pkg-config", "--cflags", "atspi-2"], text=True))
flags = [flag for flag in flags if flag.startswith(("-I", "-D", "-U"))]
header = next((pathlib.Path(flag[2:]) / "atspi/atspi.h" for flag in flags
               if flag.startswith("-I") and
               (pathlib.Path(flag[2:]) / "atspi/atspi.h").exists()), None)
if header is None:
    raise SystemExit("AT-SPI2 development headers not found")

# Zig 0.16's C translator cannot process GLib diagnostic _Pragma macros.
# Disabling diagnostic pragmas does not change any ABI declaration.
translated = subprocess.check_output(
    ["zig", "translate-c", "-lc", "-D_Pragma(x)=", *flags, str(header)],
    text=True)
functions = (
    "atspi_init", "atspi_exit", "atspi_set_timeout", "atspi_get_desktop",
    "atspi_accessible_get_child_count", "atspi_accessible_get_child_at_index",
    "atspi_accessible_get_name", "atspi_accessible_get_role",
    "atspi_accessible_get_process_id", "atspi_accessible_is_component",
    "atspi_accessible_get_component_iface", "atspi_component_get_extents",
    "g_object_unref", "g_free", "g_error_free", "g_setenv",
)
output = [
    "// Generated by scripts/generate-atspi-api.py using zig translate-c.",
    "// System types are opaque; pointer nullability is adapted for Zig callers.",
    "// Regenerate when updating the AT-SPI2 ABI; no project C source is compiled.",
    "", "pub const AtspiAccessible = opaque {};",
    "pub const AtspiComponent = opaque {};", "pub const GError = opaque {};", "",
]
coord_type = re.search(r"pub const AtspiCoordType = (\w+);", translated)
if coord_type is None:
    raise SystemExit("AtspiCoordType missing from translated declarations")
output.append(f"pub const AtspiCoordType = {coord_type[1]};")
for name in ("screen", "window", "parent"):
    constant = re.search(rf"pub const ATSPI_COORD_TYPE_{name.upper()}: \w+ = (\d+);", translated)
    if constant is None:
        raise SystemExit(f"Coordinate constant {name} not found")
    output.append(f"pub const coord_type_{name}: AtspiCoordType = {constant[1]};")
role_type = re.search(r"pub const AtspiRole = (\w+);", translated)
if role_type is None:
    raise SystemExit("AtspiRole missing from translated declarations")
output.append(f"pub const AtspiRole = {role_type[1]};")
used_roles = set(re.findall(r"api\.(ATSPI_ROLE_\w+)",
                          (root / "src/atspi/bindings.zig").read_text()))
found_roles = set()
for name, value in re.findall(r"^pub const (ATSPI_ROLE_\w+): c_int = (\d+);", translated, re.M):
    if name in used_roles:
        output.append(f"pub const {name}: AtspiRole = {value};")
        found_roles.add(name)
if used_roles != found_roles:
    raise SystemExit(f"AT-SPI headers do not define required roles: {used_roles - found_roles}")
output.extend(["", "pub const AtspiRect = extern struct {"])
rect = re.search(r"pub const struct__AtspiRect = extern struct \{(.*?)\n\};", translated, re.S)
if rect is None:
    raise SystemExit("AtspiRect missing from translated declarations")
for field in ("x", "y", "width", "height"):
    declaration = re.search(rf"\b{field}: (\w+) = 0,", rect[1])
    if declaration is None or declaration[1] != "gint":
        raise SystemExit(f"Unexpected ABI field: AtspiRect.{field}")
    output.append(f"    {field}: c_int = 0,")
output.extend(["};", ""])
for name in functions:
    declaration = re.search(rf"^pub extern fn {name}\(.*?;$", translated, re.M)
    if declaration is None:
        raise SystemExit(f"Function {name} missing from translated declarations")
    text = declaration[0].replace("atspi_exit(...)", "atspi_exit()")
    text = text.replace("[*c][*c]GError", "?*?*GError")
    text = text.replace("[*c]GError", "?*GError")
    for pointer in ("AtspiAccessible", "AtspiComponent", "AtspiRect"):
        text = text.replace(f"[*c]{pointer}", f"?*{pointer}")
    for original, replacement in (("gint", "c_int"), ("guint", "c_uint"),
                                  ("gboolean", "c_int"), ("gchar", "u8"),
                                  ("gpointer", "?*anyopaque")):
        text = re.sub(rf"\b{original}\b", replacement, text)
    output.append(text)

path = root / "src/atspi/api.zig"
path.write_text("\n".join(output) + "\n")
subprocess.run(["zig", "fmt", str(path)], check=True)
print(f"Generated {path.relative_to(root)}")
